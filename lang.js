function applyLanguage(lang) {
  lang = translations[lang] ? lang : 'de';
  const selected = translations[lang] || translations.en;
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (selected[key]) {
      element.textContent = selected[key];
    }
  });

  document.querySelectorAll('.lang-toggle').forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === lang);
  });

  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    const value = selected[element.dataset.i18nAlt];
    if (value) element.alt = value;
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const value = selected[element.dataset.i18nAriaLabel];
    if (value) element.setAttribute('aria-label', value);
  });

  const page = document.body.dataset.page;
  const pageTitle = page ? selected[`${page}.metaTitle`] : '';
  if (pageTitle) {
    document.title = pageTitle;
  }

  const pageDescription = page ? selected[`${page}.metaDescription`] : '';
  const description = document.querySelector('meta[name="description"]');
  if (description && pageDescription) description.content = pageDescription;

  try { localStorage.setItem('site-lang', lang); } catch (_) {}
}

function initLanguageSwitcher() {
  let savedLang = 'de';
  try { savedLang = localStorage.getItem('site-lang') || 'de'; } catch (_) {}
  document.querySelectorAll('.lang-toggle').forEach((button) => {
    button.addEventListener('click', () => applyLanguage(button.dataset.lang));
  });
  applyLanguage(savedLang);
}

function initContactForm() {
  const form = document.querySelector('#contact-form');
  if (!form) {
    return;
  }

  const topicSelect = form.querySelector('#contact-topic');
  const submitButton = form.querySelector('.form-submit');
  const status = form.querySelector('#contact-status');

  const fields = {
    name: form.querySelector('#contact-name'),
    email: form.querySelector('#contact-email'),
    message: form.querySelector('#contact-message'),
    privacy: form.querySelector('#contact-privacy')
  };

  const errors = {
    name: form.querySelector('#contact-name-error'),
    email: form.querySelector('#contact-email-error'),
    message: form.querySelector('#contact-message-error'),
    privacy: form.querySelector('#contact-privacy-error')
  };

  const messages = {
    name: 'Bitte geben Sie Ihren Namen ein.',
    email: 'Bitte geben Sie eine gültige E-Mail-Adresse ein.',
    message: 'Bitte beschreiben Sie kurz Ihr Anliegen.',
    privacy: 'Bitte bestätigen Sie die Datenschutzerklärung.',
    success: 'Vielen Dank für Ihre Anfrage! Wir haben Ihre Nachricht erhalten und melden uns so bald wie möglich bei Ihnen.',
    error: 'Ihre Nachricht konnte leider nicht gesendet werden. Bitte versuchen Sie es noch einmal oder kontaktieren Sie uns direkt per E-Mail.'
  };

  function setFieldError(key, message) {
    const field = fields[key];
    const error = errors[key];
    if (!field || !error) {
      return;
    }

    field.setAttribute('aria-invalid', message ? 'true' : 'false');
    field.setAttribute('aria-describedby', error.id);
    error.textContent = message;
  }

  function setStatus(message, type) {
    status.textContent = message;
    status.className = `form-status is-visible is-${type}`;
  }

  function clearStatus() {
    status.textContent = '';
    status.className = 'form-status';
  }

  function validateForm() {
    let isValid = true;
    const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

    if (!fields.name.value.trim()) {
      setFieldError('name', messages.name);
      isValid = false;
    } else {
      setFieldError('name', '');
    }

    if (!emailPattern.test(fields.email.value.trim())) {
      setFieldError('email', messages.email);
      isValid = false;
    } else {
      setFieldError('email', '');
    }

    if (!fields.message.value.trim()) {
      setFieldError('message', messages.message);
      isValid = false;
    } else {
      setFieldError('message', '');
    }

    if (!fields.privacy.checked) {
      setFieldError('privacy', messages.privacy);
      isValid = false;
    } else {
      setFieldError('privacy', '');
    }

    return isValid;
  }

  document.querySelectorAll('.contact-topic-link').forEach((link) => {
    link.addEventListener('click', () => {
      const topic = link.dataset.contactTopic;
      if (topic && topicSelect) {
        topicSelect.value = topic;
      }
    });
  });

  form.addEventListener('submit', async (event) => {
    event.preventDefault();
    clearStatus();

    if (!validateForm()) {
      return;
    }

    const formData = new FormData(form);
    const payload = Object.fromEntries(formData.entries());
    payload.privacy = fields.privacy.checked;

    submitButton.disabled = true;
    submitButton.textContent = submitButton.dataset.loadingText;

    try {
      const response = await fetch(form.action, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json'
        },
        body: JSON.stringify(payload)
      });

      const result = await response.json().catch(() => ({ success: false }));
      if (!response.ok || !result.success) {
        throw new Error('Contact request failed');
      }

      form.reset();
      topicSelect.value = 'Sonstiges / Noch nicht sicher';
      Object.keys(errors).forEach((key) => setFieldError(key, ''));
      setStatus(messages.success, 'success');
    } catch (error) {
      console.error('Contact form submission failed.');
      setStatus(messages.error, 'error');
    } finally {
      submitButton.disabled = false;
      submitButton.textContent = submitButton.dataset.defaultText;
    }
  });
}

function initBackToTopButton() {
  const button = document.querySelector('.back-to-top');
  if (!button) {
    return;
  }

  function updateVisibility() {
    button.classList.toggle('is-visible', window.scrollY > 320);
  }

  updateVisibility();
  window.addEventListener('scroll', updateVisibility, { passive: true });
}

initLanguageSwitcher();
initContactForm();
initBackToTopButton();
